from __future__ import annotations

from datetime import UTC, datetime

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    Computed,
    DateTime,
    ForeignKey,
    Index,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import TSVECTOR
from sqlalchemy.orm import Mapped, mapped_column, relationship

from medagent.db.base import Base

EMBEDDING_DIM = 384  # BAAI/bge-small-en-v1.5; changing it needs a new migration + re-ingest


def _utcnow() -> datetime:
    return datetime.now(UTC)


class KbDocument(Base):
    """One source document (a PDF, a MedlinePlus topic...) with its licence and attribution."""

    __tablename__ = "kb_documents"
    __table_args__ = (UniqueConstraint("source_key", "external_id"),)

    id: Mapped[int] = mapped_column(primary_key=True)
    source_key: Mapped[str] = mapped_column(String(40), index=True)  # e.g. "medlineplus"
    external_id: Mapped[str] = mapped_column(String(200))  # stable id within the source
    title: Mapped[str] = mapped_column(String(300))
    url: Mapped[str | None] = mapped_column(String(500))
    license: Mapped[str] = mapped_column(String(120))
    attribution: Mapped[str] = mapped_column(String(300))
    is_public: Mapped[bool] = mapped_column(index=True)  # False = local dev only, never deployed
    content_hash: Mapped[str] = mapped_column(String(64))  # sha256 of text: skip unchanged docs
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), default=_utcnow, onupdate=_utcnow
    )

    chunks: Mapped[list[KbChunk]] = relationship(
        back_populates="document", cascade="all, delete-orphan"
    )


class KbChunk(Base):
    __tablename__ = "kb_chunks"
    __table_args__ = (
        UniqueConstraint("document_id", "chunk_index"),
        Index(
            "ix_kb_chunks_embedding_hnsw",
            "embedding",
            postgresql_using="hnsw",
            postgresql_with={"m": 16, "ef_construction": 64},
            postgresql_ops={"embedding": "vector_cosine_ops"},
        ),
        Index("ix_kb_chunks_tsv", "tsv", postgresql_using="gin"),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    document_id: Mapped[int] = mapped_column(
        ForeignKey("kb_documents.id", ondelete="CASCADE"), index=True
    )
    chunk_index: Mapped[int]
    page: Mapped[int | None]  # 1-based page for PDFs, None for web/XML sources
    content: Mapped[str] = mapped_column(Text)
    embedding: Mapped[list[float]] = mapped_column(Vector(EMBEDDING_DIM))
    # Generated by Postgres from `content`; used for keyword (full-text) search.
    tsv: Mapped[str] = mapped_column(
        TSVECTOR, Computed("to_tsvector('english', content)", persisted=True)
    )

    document: Mapped[KbDocument] = relationship(back_populates="chunks")
